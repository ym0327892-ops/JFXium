import java.nio.file.Files;
import java.nio.file.Path;

/**
 * 把 Skill 打包成**单文件**，用于直接粘贴给任意 AI（聊天窗口 / 不支持 Skill 的工具）。
 *
 * <pre>{@code
 * java skills/jfxium/scripts/Bundle.java
 * # -> skills/jfxium/dist/jfxium-skill.md
 * }</pre>
 *
 * <p>产物 = {@code SKILL.md} 正文（去掉 YAML frontmatter）+ 组件速查索引。
 * 生成物需提交；CI 会校验漂移。</p>
 */
public final class Bundle {

    public static void main(String[] args) throws Exception {
        Path skill = Path.of(arg(args, "--skill", "skills/jfxium"));
        Path out = Path.of(arg(args, "--out", "skills/jfxium/dist/jfxium-skill.md"));

        String body = stripFrontmatter(Files.readString(skill.resolve("SKILL.md")));
        Path index = skill.resolve("assets/catalog/components.index.md");
        String catalog = Files.exists(index) ? Files.readString(index) : "";

        StringBuilder bundle = new StringBuilder();
        bundle.append("<!--\n")
                .append("  JFXium single-file agent bundle.\n")
                .append("  Generated by skills/jfxium/scripts/Bundle.java — do not edit.\n")
                .append("  Source: skills/jfxium/SKILL.md + assets/catalog/components.index.md\n")
                .append("-->\n\n")
                .append(body.strip()).append("\n\n---\n\n")
                .append(catalog.strip()).append('\n');

        if (out.getParent() != null) {
            Files.createDirectories(out.getParent());
        }
        Files.writeString(out, bundle);
        System.out.printf("bundle: %d chars -> %s%n", bundle.length(), out.toAbsolutePath());
    }

    /** 去掉文件头部的 YAML frontmatter（`---` ... `---`），保留正文。 */
    private static String stripFrontmatter(String text) {
        String s = text.stripLeading();
        if (!s.startsWith("---")) {
            return s;
        }
        int end = s.indexOf("\n---", 3);
        if (end < 0) {
            return s;
        }
        int bodyStart = s.indexOf('\n', end + 4);
        return bodyStart < 0 ? "" : s.substring(bodyStart + 1);
    }

    private static String arg(String[] args, String name, String fallback) {
        for (int i = 0; i < args.length - 1; i++) {
            if (args[i].equals(name)) {
                return args[i + 1];
            }
        }
        return fallback;
    }
}
